// Generates ios/CodecMobile/App/Themes.generated.swift from the desktop theme
// definitions, so the desktop stays the single source of truth:
//   - names + swatches from src/lib/themes.ts
//   - colors from the :root block and [data-theme] blocks in src/app.css
//
// Run with: bun run gen:ios-themes

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(repo, "src/app.css"), "utf8");
const themesTS = readFileSync(join(repo, "src/lib/themes.ts"), "utf8");
const outPath = join(repo, "ios/CodecMobile/App/Themes.generated.swift");

// --- themes.ts: ordered ids, display names, swatches -----------------------

const themeEntries = [...themesTS.matchAll(
  /\{ id: "([^"]+)", name: "([^"]+)", swatch: \["([^"]+)", "([^"]+)", "([^"]+)"\] \}/g
)].map(([, id, name, a, b, c]) => ({ id, name, swatch: [a, b, c] }));

if (themeEntries.length === 0) {
  throw new Error("no themes parsed from src/lib/themes.ts");
}

// --- app.css: variable blocks ----------------------------------------------

function parseVars(block) {
  const vars = {};
  for (const [, name, value] of block.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)) {
    vars[name] = value.trim();
  }
  return vars;
}

const rootBlock = css.match(/:root\s*\{([\s\S]*?)\n\}/);
if (!rootBlock) {
  throw new Error("no :root block found in src/app.css");
}
const rootVars = parseVars(rootBlock[1]);

// Theme blocks, including grouped selectors, applied in file order.
const themeVars = Object.fromEntries(themeEntries.map(({ id }) => [id, { ...rootVars }]));
for (const match of css.matchAll(/((?:\[data-theme="[^"]+"\],?\s*)+)\{([\s\S]*?)\n\}/g)) {
  const ids = [...match[1].matchAll(/\[data-theme="([^"]+)"\]/g)].map(([, id]) => id);
  const vars = parseVars(match[2]);
  for (const id of ids) {
    if (themeVars[id]) {
      Object.assign(themeVars[id], vars);
    }
  }
}

// --- color conversion --------------------------------------------------------

function parseColor(value) {
  if (!value) {
    return null;
  }
  const hex = value.match(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i);
  if (hex) {
    let digits = hex[1];
    if (digits.length === 3) {
      digits = [...digits].map((d) => d + d).join("");
    }
    const n = parseInt(digits, 16);
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: 1 };
  }
  const rgba = value.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
  if (rgba) {
    return { r: +rgba[1], g: +rgba[2], b: +rgba[3], a: rgba[4] === undefined ? 1 : +rgba[4] };
  }
  return null; // color-mix() and friends: callers must provide a fallback
}

function swiftColor(color) {
  const f = (n) => {
    const s = (n / 255).toFixed(4).replace(/0+$/, "").replace(/\.$/, "");
    return s === "" ? "0" : s;
  };
  const base = `Color(red: ${f(color.r)}, green: ${f(color.g)}, blue: ${f(color.b)}`;
  return color.a === 1 ? `${base})` : `${base}, opacity: ${color.a})`;
}

function luminance({ r, g, b }) {
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}

// --- emit -------------------------------------------------------------------

const fields = [
  ["bg", "--color-bg"],
  ["panel", "--color-panel"],
  ["panel2", "--color-panel-2"],
  ["surface", "--color-surface"],
  ["surfaceHover", "--color-surface-hover"],
  ["border", "--color-border"],
  ["line", "--color-line"],
  ["text", "--color-text"],
  ["muted", "--color-muted"],
  ["subtle", "--color-subtle"],
  ["accent", "--color-accent"],
  ["accentHover", "--color-accent-hover"],
  ["danger", "--color-danger"],
  ["button", "--button-bg"],
  ["buttonHover", "--button-bg-hover"],
  ["buttonActive", "--button-bg-active"],
  ["buttonShadow", "--button-shadow"],
  ["accentText", "--button-primary-text"],
  ["glint", "--color-glint"],
];

const themes = themeEntries.map(({ id, name, swatch }) => {
  const vars = themeVars[id];
  const lines = [`        id: "${id}",`, `        name: "${name}",`];
  for (const [field, varName] of fields) {
    const color = parseColor(vars[varName]);
    if (!color) {
      throw new Error(`theme "${id}": cannot parse ${varName} = ${vars[varName]}`);
    }
    lines.push(`        ${field}: ${swiftColor(color)},`);
  }
  const swatchColors = swatch.map((hex) => swiftColor(parseColor(hex)));
  lines.push(`        swatch: [${swatchColors.join(", ")}],`);
  lines.push(`        isLight: ${luminance(parseColor(vars["--color-bg"])) > 0.5}`);
  return `    CodecTheme(\n${lines.join("\n")}\n    )`;
});

const output = `// Generated by scripts/generate-ios-themes.mjs — do not edit.
// Source of truth: src/lib/themes.ts + src/app.css. Regenerate with:
//   bun run gen:ios-themes

import SwiftUI

let codecThemes: [CodecTheme] = [
${themes.join(",\n")}
]
`;

writeFileSync(outPath, output);
console.log(`wrote ${themes.length} themes to ${outPath}`);
